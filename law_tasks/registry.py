"""Registration of a freshly predicted model in the performance configurations.

Instead of editing the configurations that are tracked in git, a small module
is generated per model.  It imports the base configuration (so all the models
that are active there are still drawn) and adds the entries of the new model.
The tracked configuration can additionally be updated in place with
``--update-base-config``.
"""

import importlib.util
import json
import os
import pprint
import re
import sys

from law_tasks import naming
from law_tasks.config import settings

GENERATED_HEADER = '''"""Generated by the law task hh4b.RegisterModel -- do not edit by hand.

Model: {key}
Base configuration: {base}
"""

import importlib.util as _importlib_util
import os as _os

_BASE_CONFIG = "{base}"


def _load_base(path):
    spec = _importlib_util.spec_from_file_location(
        "law_base_" + _os.path.splitext(_os.path.basename(path))[0], path
    )
    module = _importlib_util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_base = _load_base(_BASE_CONFIG)

MODEL_KEY = {key_literal}
TRUE_KEY = {true_key_literal}

# the Run 2 method is evaluated on the true file of this model, the one the
# model is compared against, and not on the one of the base configuration
run2_dataset_MC = {run2_mc}
run2_dataset_DATA = getattr(_base, "run2_dataset_DATA", "")
roc_dict = dict(getattr(_base, "roc_dict", {{}}))

spanet_dict = {baseline}
true_dict = dict(_base.true_dict)

{spanet_entry}

{true_entry}


# ---------------------------------------------------------------------------
# the new entries, ready to be copied into the base configuration
# ---------------------------------------------------------------------------

{spanet_comment}


{true_comment}
'''

# line length of the generated modules, the black default
LINE_LENGTH = 88


def load_config_module(path):
    """Import a performance configuration module from its file path."""
    path = os.path.abspath(path)
    name = "law_cfg_" + os.path.splitext(os.path.basename(path))[0]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def used_colors(modules):
    """Colors already taken by an active entry of any of ``modules``."""
    colors = []
    for module in modules:
        for entry in getattr(module, "spanet_dict", {}).values():
            color = entry.get("color")
            if color:
                colors.append(color)
    return colors


def resolve_true_key(modules, test_file, fallback):
    """Return the ``true_dict`` key to use for ``test_file``.

    Models that only differ by a training setting share their truth file; by
    matching on the resolved path the pipeline reuses the key that is already
    there instead of adding a duplicate.  When the derived key is taken by a
    *different* file, a numbered suffix is appended so nothing is overwritten.
    """
    target = os.path.realpath(os.path.expandvars(test_file))

    known = {}
    for module in modules:
        for key, entry in getattr(module, "true_dict", {}).items():
            name = entry.get("name")
            if not name:
                continue
            path = os.path.realpath(os.path.expandvars(name))
            if path == target:
                return key, True
            known.setdefault(key, path)

    key, index = fallback, 1
    while key in known:
        index += 1
        key = "{}_v{}".format(fallback, index)
    return key, False


def build_entries(
    key,
    prediction_file,
    test_file,
    color,
    label=None,
    true_key=None,
    higgs=True,
    vbf=True,
    klambda=None,
    extra_spanet=None,
    extra_true=None,
):
    """Build the ``spanet_dict`` and ``true_dict`` entries of one model.

    ``higgs`` and ``vbf`` say which pairings the prediction holds, which is
    what ``efficiency_studies.py`` asks the entry for before computing an
    efficiency; both are written, so the entry says what the file does not
    have as well.
    """
    token_spanet, token_true = naming.extra_entries(key)

    spanet_entry = {
        "file": prediction_file,
        "true": true_key or naming.derive_true_key(key),
        "label": label or naming.derive_label(key),
        "color": color,
        "higgs": bool(higgs),
        "vbf": bool(vbf),
    }
    spanet_entry.update(token_spanet)
    spanet_entry.update(extra_spanet or {})

    true_entry = {"name": test_file, "klambda": klambda or settings().klambda}
    true_entry.update(token_true)
    true_entry.update(extra_true or {})

    return spanet_entry, true_entry


def _literal(value):
    """Python source of ``value``, with double quoted strings as black writes them."""
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (list, tuple, dict)):
        return pprint.pformat(value, width=LINE_LENGTH, sort_dicts=False).replace(
            "'", '"'
        )
    return repr(value)


def _item_lines(name, value, indent):
    """``"name": value,`` at ``indent``, a long string split at its spaces."""
    pad = " " * indent
    head = "{}{}: ".format(pad, _literal(name))
    line = head + _literal(value) + ","
    if len(line) <= LINE_LENGTH or not isinstance(value, str) or " " not in value:
        return [line]

    # implicit concatenation, continued at the indentation of the key
    chunks, current = [], ""
    for word in re.findall(r"\S+\s*", value):
        width = len(head if not chunks else pad) + len(_literal(current + word))
        if current and width > LINE_LENGTH:
            chunks.append(current)
            current = word
        else:
            current += word
    chunks.append(current)

    lines = [head + _literal(chunks[0])]
    lines += [pad + _literal(chunk) for chunk in chunks[1:]]
    lines[-1] += ","
    return lines


def _dict_lines(entry, indent):
    lines = []
    for name, value in entry.items():
        lines += _item_lines(name, value, indent)
    return lines


def _assignment(target, entry):
    """``<target> = {...}`` with one item per line."""
    return "\n".join(["{} = {{".format(target)] + _dict_lines(entry, 4) + ["}"])


def _commented_entry(key, entry):
    """The ``"key": {...},`` item of a dictionary, commented out."""
    lines = ["{}: {{".format(_literal(key))] + _dict_lines(entry, 4) + ["},"]
    return "\n".join("# " + line for line in lines)


def format_source(source):
    """Format with black when it is installed; the source is black style anyway."""
    try:
        import black
    except ImportError:
        return source
    try:
        return black.format_str(source, mode=black.Mode(line_length=LINE_LENGTH))
    except Exception:  # noqa: BLE001 - keep the unformatted, still valid source
        return source


def render_module(
    key,
    base_config,
    spanet_entry,
    true_key,
    true_entry,
    baseline_models="all",
    run2_dataset="",
):
    """Return the source code of the generated configuration module.

    ``run2_dataset`` is the ``true_dict`` key the Run 2 method is evaluated
    on: empty means this model's own true entry, so that both are measured on
    the same file, ``base`` keeps whatever the base configuration points at,
    and anything else is taken as that key.
    """
    if baseline_models == "all":
        baseline = "dict(_base.spanet_dict)"
    elif baseline_models in ("none", ""):
        baseline = "{}"
    else:
        keep = [m.strip() for m in baseline_models.split(",") if m.strip()]
        baseline = (
            "{{k: v for k, v in _base.spanet_dict.items() if k in {}}}".format(
                _literal(keep)
            )
        )

    if run2_dataset in ("base", "_base"):
        run2_mc = 'getattr(_base, "run2_dataset_MC", "")'
    elif not run2_dataset or run2_dataset == true_key:
        run2_mc = "TRUE_KEY"
    else:
        run2_mc = _literal(run2_dataset)

    source = GENERATED_HEADER.format(
        key=key,
        base=os.path.abspath(base_config),
        key_literal=_literal(key),
        true_key_literal=_literal(true_key),
        baseline=baseline,
        run2_mc=run2_mc,
        spanet_entry=_assignment("spanet_dict[MODEL_KEY]", spanet_entry),
        true_entry=_assignment("true_dict[TRUE_KEY]", true_entry),
        spanet_comment=_commented_entry(key, spanet_entry),
        true_comment=_commented_entry(true_key, true_entry),
    )
    return format_source(source)


def write_module(path, source):
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w") as fobj:
        fobj.write(source)
    return path


